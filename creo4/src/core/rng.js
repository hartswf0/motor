// Deterministic randomness. CREO must reproduce a world exactly from its event log,
// so nothing in the world engine is allowed to call Math.random().

export function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function hashString(str) {
  let h = 2166136261 >>> 0;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/** A named, seekable random stream. Same name + same seed → same numbers, forever. */
export function stream(name, seed = 0) {
  return mulberry32(hashString(name) ^ (seed >>> 0));
}
