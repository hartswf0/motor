const FT_PER_M = 3.280839895013123;
const M_PER_DEG_LAT = 111319.49079327358;

export function lonLatToLocalFt(lon, lat, anchor = SITE_CONTEXT.anchor) {
  const c = Math.cos(anchor.lat * Math.PI / 180);
  return {
    east: (lon - anchor.lon) * M_PER_DEG_LAT * c * FT_PER_M,
    north: (lat - anchor.lat) * M_PER_DEG_LAT * FT_PER_M,
  };
}

export function localFtToLonLat(eastFt, northFt, anchor = SITE_CONTEXT.anchor) {
  const c = Math.cos(anchor.lat * Math.PI / 180);
  return {
    lon: anchor.lon + eastFt / (M_PER_DEG_LAT * c * FT_PER_M),
    lat: anchor.lat + northFt / (M_PER_DEG_LAT * FT_PER_M),
  };
}

